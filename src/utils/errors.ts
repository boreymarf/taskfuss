import { AppError } from "@/generated/bindings";
import { error as logError } from "@utils/logger";

/**
 * Extracts the required (non-optional) keys of `T` as a string union.
 *
 * Used to find the "active" variant tag in a Specta-generated error object:
 * Specta emits placeholder keys typed as optional `never` for the other variants,
 * and this type filters them out, leaving only the real tag.
 *
 * Example:
 * ```ts
 * type A = { A: 1 } & { B?: never };
 * type Tags = RequiredKeys<A>; // "A"
 * ```
 */
type RequiredKeys<T> = {
  [K in keyof T]-?: {} extends Pick<T, K> ? never : K;
}[keyof T] & string;

/**
 * Union of all possible tags of a Specta error type `T`.
 * - If `T` is a plain string (unit variant like "Required"), the tag is that string.
 * - Otherwise, the tag is the single required key of each object variant.
 *
 * Example:
 * ```ts
 * type E =
 *   | "Required"
 *   | ({ WrongType: { expected: string } } & { TooShort?: never });
 * type Tags = SpectaErrorTag<E>; // "Required" | "WrongType"
 * ```
 */
export type SpectaErrorTag<T> = T extends string ? T : RequiredKeys<T>;

/**
 * Payload type for a given `Tag` within error type `T`.
 * - String variant: returns `undefined` when `T` equals `Tag` (no data attached).
 * - Object variant, tag belongs to this variant: returns `T[Tag]` with `undefined` stripped.
 * - Object variant, tag does NOT belong to this variant: returns `never`.
 *
 * Example:
 * ```ts
 * type E =
 *   | "Required"
 *   | ({ WrongType: { expected: string } } & { TooShort?: never });
 * type P1 = PayloadOf<E, "Required">;  // undefined
 * type P2 = PayloadOf<E, "WrongType">; // { expected: string }
 * ```
 */
type PayloadOf<T, Tag extends string> =
  | (T extends string ? (T extends Tag ? undefined : never) : never)
  | (T extends object
      ? Tag extends keyof T
        ? NonNullable<T[Tag]>
        : never
      : never);

/**
 * Map from every tag of `T` to its payload type.
 *
 * Example:
 * ```ts
 * type E =
 *   | "Required"
 *   | ({ WrongType: { expected: string } } & { TooShort?: never });
 * type P = SpectaErrorPayloads<E>;
 * // { "Required": undefined; "WrongType": { expected: string } }
 * ```
 */
export type SpectaErrorPayloads<T> = {
  [K in SpectaErrorTag<T>]: PayloadOf<T, K>;
};

/**
 * Discriminated union of `{ tag, payload }` entries for every variant of `T`.
 * Lets you `switch (entry.tag)` and get a narrowed `entry.payload`.
 *
 * Example:
 * ```ts
 * type E =
 *   | "Required"
 *   | ({ WrongType: { expected: string } } & { TooShort?: never });
 * type Entry = SpectaErrorEntry<E>;
 * //   | { tag: "Required";  payload: undefined }
 * //   | { tag: "WrongType"; payload: { expected: string } }
 *
 * declare const e: Entry;
 * if (e.tag === "WrongType") {
 *   e.payload.expected; // string
 * }
 * ```
 */
export type SpectaErrorEntry<T extends string | object> = {
  [K in SpectaErrorTag<T>]: { tag: K; payload: SpectaErrorPayloads<T>[K] };
}[SpectaErrorTag<T>];

/**
 * Runtime converter: turns a Specta error value (`"Required"` or `{ WrongType: {...} }`)
 * into a `{ tag, payload }` entry for easy pattern matching.
 * Throws if no active tag is found in the object.
 *
 * Example:
 * ```ts
 * const a = extractSpectaError("Required");
 * // { tag: "Required", payload: undefined }
 *
 * const b = extractSpectaError({ WrongType: { expected: "u32" } });
 * // { tag: "WrongType", payload: { expected: "u32" } }
 * ```
 */
export function extractSpectaError<T extends string | object>(
  err: T,
): SpectaErrorEntry<T> {
  if (typeof err === "string") {
    return { tag: err, payload: undefined } as SpectaErrorEntry<T>;
  }

  const entries = Object.entries(err as Record<string, unknown>);
  for (const [key, value] of entries) {
    if (value !== undefined) {
      return { tag: key, payload: value } as SpectaErrorEntry<T>;
    }
  }

  throw new Error(`Invalid specta error: no active tag in ${JSON.stringify(err)}`);
}

/**
 * Detail type of a specific `K` variant of `AppError`.
 *
 * `AppError` is a discriminated union generated by Specta:
 * `{ kind: "plan"; detail: PlanError } | { kind: "form"; detail: FormError } | ...`.
 * Picking one variant's detail via `Extract<AppError, { kind: K }>` does not work
 * when `K` is a generic type parameter (TS collapses it to `never`), so this
 * helper uses a distributive conditional instead.
 *
 * The second parameter `E` exists only to make the conditional distributive:
 * without it, `AppError extends { kind: K; detail: infer D } ? D : never`
 * would check the whole union at once instead of each variant separately.
 *
 * Example:
 * ```ts
 * type D1 = DetailOf<"form">;        // FormError
 * type D2 = DetailOf<"internal">;    // string
 * ```
 */
type DetailOf<K extends AppError["kind"], E extends AppError = AppError> =
  E extends { kind: K; detail: infer D } ? D : never;

/**
 * Narrows an `AppError` to a specific `kind` and returns its `detail`.
 * Returns `undefined` for a mismatch and logs it via the Tauri logger,
 * so unexpected backend shapes are visible instead of silently swallowed.
 *
 * The return type is the exact detail type for the given `kind`,
 * so the caller does not need to cast or narrow further.
 *
 * Example:
 * ```ts
 * const e: AppError = ...;
 *
 * const formError = unwrapAppError(e, "form");
 * // FormError | undefined
 *
 * const internalMessage = unwrapAppError(e, "internal");
 * // string | undefined
 *
 * const wrong = unwrapAppError(e, "plan");
 * // undefined + log: Expected AppError kind "plan", got "form": {...}
 * ```
 */
export function unwrapAppError<K extends AppError["kind"]>(
  err: AppError,
  kind: K,
): DetailOf<K> | undefined {
  if (err.kind !== kind) {
    logError(`Expected AppError kind "${kind}", got "${err.kind}": ${JSON.stringify(err)}`);
    return undefined;
  }
  return err.detail as DetailOf<K>;
}